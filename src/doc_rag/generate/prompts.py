def format_context(chunks: list[dict]) -> str:
    """chunks: [{"no": 1, "text": ..., "doc": ..., "page": ...}] → 编号上下文块。"""
    parts = []
    for c in chunks:
        loc = f"（{c['doc']}" + (f" 第{c['page']}页" if c.get("page") else "") + "）"
        parts.append(f"[{c['no']}] {loc}\n{c['text']}")
    return "\n\n".join(parts)


